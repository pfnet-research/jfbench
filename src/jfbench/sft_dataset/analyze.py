from __future__ import annotations

import argparse
from collections import Counter
from collections import defaultdict
from dataclasses import dataclass
from itertools import tee
from pathlib import Path
import re
from typing import Any
from typing import Iterable
from typing import Iterator
from typing import Mapping
from typing import Sequence

from pyarrow import ArrowInvalid
import pyarrow.ipc as pa_ipc

import jfbench.constraints as all_constraints


SUPPORTED_SUFFIXES = {".arrow"}
DEFAULT_DATASET_PATH = "data/generated_dataset"


@dataclass(frozen=True)
class ConstraintStats:
    total_records: int
    counts_by_constraint_total: dict[int, int]
    counts_by_prompt_and_constraint_count: dict[str, dict[int, int]]
    per_constraint_counts: dict[int, dict[str, dict[str, int]]]


def parse_args(argv: Sequence[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Analyze a dataset generated by jfbench and show constraint statistics."
    )
    parser.add_argument(
        "dataset_paths",
        nargs="*",
        default=("data/dpo_dataset",),
        help="Paths to HuggingFace Dataset directories.",
    )
    parser.add_argument(
        "--show-generated",
        action="store_true",
        help="Show prompt, response, and reasoning content for each data entry.",
    )
    return parser.parse_args(argv)


def discover_data_files(base_paths: Sequence[Path]) -> list[Path]:
    if not base_paths:
        raise ValueError("No dataset paths provided.")
    discovered_files: list[Path] = []
    for base_path in base_paths:
        if base_path.is_file():
            if base_path.suffix not in SUPPORTED_SUFFIXES:
                raise ValueError(f"Unsupported file type: {base_path.suffix}")
            discovered_files.append(base_path)
            continue
        if not base_path.exists():
            print(f"Dataset path '{base_path}' does not exist.")
            continue
        files = sorted(
            path
            for path in base_path.rglob("*")
            if path.is_file() and path.suffix in SUPPORTED_SUFFIXES
        )
        if not files:
            raise FileNotFoundError(
                f"No Arrow files found under '{base_path}'. Did you point to the dataset root?"
            )
        discovered_files.extend(files)
    return discovered_files


def iter_rows(files: Sequence[Path]) -> Iterator[Mapping[str, Any]]:
    for file_path in files:
        if file_path.suffix == ".arrow" and "cache" not in str(file_path):
            yield from _iter_arrow_rows(file_path)


def _iter_arrow_rows(file_path: Path) -> Iterator[Mapping[str, Any]]:
    try:
        reader_ctx = pa_ipc.open_file(file_path)
    except ArrowInvalid:
        try:
            reader_ctx = pa_ipc.open_stream(file_path)
        except ArrowInvalid as exc:  # pragma: no cover - defensive
            raise ValueError(f"{file_path} is not a valid Arrow IPC file or stream") from exc
    with reader_ctx as reader:
        for batch in _iter_reader_batches(reader):
            for row in batch.to_pylist():
                if isinstance(row, Mapping):
                    yield row


def _iter_reader_batches(reader: Any) -> Iterator[Any]:
    if hasattr(reader, "iter_batches"):
        yield from reader.iter_batches()
        return
    while True:
        try:
            batch = reader.read_next_batch()
        except StopIteration:  # pragma: no cover - defensive
            break
        if batch is None:
            break
        yield batch


def compute_constraint_stats(
    rows: Iterable[Mapping[str, Any]],
) -> ConstraintStats:
    total_records = 0
    count_totals: Counter[int] = Counter()
    counts_by_prompt_and_constraint: dict[str, Counter[int]] = defaultdict(Counter)
    per_constraint: dict[int, dict[str, Counter[str]]] = defaultdict(lambda: defaultdict(Counter))
    for row in rows:
        count = _resolve_constraint_count(row)
        total_records += 1
        count_totals[count] += 1
        prompt_source = _normalize_prompt_source(row.get("prompt_source"))
        if prompt_source:
            counts_by_prompt_and_constraint[prompt_source][count] += 1
        for group, name in _iter_constraint_pairs(row):
            per_constraint[count][group][name] += 1
    sorted_counts = dict(sorted(count_totals.items()))
    constraint_catalog = _build_constraint_catalog()
    sorted_constraint_counts = {
        count: _expand_constraint_counts(group_counters, constraint_catalog)
        for count, group_counters in sorted(per_constraint.items())
    }
    sorted_prompt_counts = {
        prompt_source: dict(sorted(counter.items()))
        for prompt_source, counter in sorted(counts_by_prompt_and_constraint.items())
    }
    return ConstraintStats(
        total_records=total_records,
        counts_by_constraint_total=sorted_counts,
        counts_by_prompt_and_constraint_count=sorted_prompt_counts,
        per_constraint_counts=sorted_constraint_counts,
    )


def format_stats(stats: ConstraintStats) -> str:
    lines = [f"Total data: {stats.total_records}"]
    lines.append("Total data per constraint count:")
    if stats.counts_by_constraint_total:
        for count, total in stats.counts_by_constraint_total.items():
            lines.append(f"  {count}: {total}")
    else:
        lines.append("  (no data)")
    lines.append("Total data per prompt source and constraint count:")
    if stats.counts_by_prompt_and_constraint_count:
        for prompt_source, counts in stats.counts_by_prompt_and_constraint_count.items():
            lines.append(f"  {prompt_source}:")
            for count, total in counts.items():
                lines.append(f"    {count}: {total}")
    else:
        lines.append("  (no data)")
    lines.append("Constraint breakdown by constraint count:")
    if stats.per_constraint_counts:
        for count, group_counters in stats.per_constraint_counts.items():
            lines.append(f"  {count}:")
            for group, counters in group_counters.items():
                lines.append(f"    {group}:")
                for name, total in counters.items():
                    lines.append(f"      {name}: {total}")
    else:
        lines.append("  (no data)")
    return "\n".join(lines)


def _resolve_constraint_count(row: Mapping[str, Any]) -> int:
    value = row.get("constraint_count")
    if isinstance(value, bool):
        return int(value)
    if isinstance(value, (int, float)):
        return int(value)
    constraints = row.get("constraints") or []
    if isinstance(constraints, Sequence):
        return len(constraints)
    return 0


def _iter_constraint_pairs(row: Mapping[str, Any]) -> Iterator[tuple[str, str]]:
    groups = _normalize_string_sequence(row.get("constraint_groups"))
    constraints = row.get("constraints") or []
    yielded = False
    if isinstance(constraints, Sequence) and not isinstance(constraints, (str, bytes)):
        for idx, constraint in enumerate(constraints):
            if not isinstance(constraint, Mapping):
                continue
            name = constraint.get("name")
            if not isinstance(name, str) or not name:
                continue
            group = constraint.get("group")
            if (not isinstance(group, str) or not group) and idx < len(groups):
                group = groups[idx]
            yield (_normalize_group_name(group), name)
            yielded = True
        if yielded:
            return
    names = _normalize_string_sequence(row.get("constraint_types"))
    length = min(len(names), len(groups))
    if length:
        for idx in range(length):
            yield (_normalize_group_name(groups[idx]), names[idx])
        return
    for name in names:
        yield (_normalize_group_name(None), name)


def _normalize_string_sequence(value: object) -> list[str]:
    if value is None:
        return []
    if isinstance(value, str):
        return [value]
    if isinstance(value, Sequence) and not isinstance(value, (str, bytes)):
        result: list[str] = []
        for item in value:
            if item is None:
                continue
            result.append(str(item))
        return result
    return [str(value)]


def _normalize_group_name(value: object) -> str:
    if isinstance(value, str):
        stripped = value.strip()
        with_underscores = re.sub(r"(.)([A-Z][a-z]+)", r"\1_\2", stripped)
        with_underscores = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", with_underscores)
        normalized = re.sub(r"[\s-]+", "_", with_underscores).lower()
        if normalized:
            return normalized
    return "unknown"


def _normalize_prompt_source(value: object | None) -> str | None:
    if value is None:
        return None
    normalized = str(value).strip()
    if not normalized:
        return None
    return normalized


def _build_constraint_catalog() -> dict[str, list[str]]:
    grouped: dict[str, list[str]] = defaultdict(list)
    for name in sorted(all_constraints.__all__):
        constraint = getattr(all_constraints, name, None)
        grouped[_infer_constraint_group(constraint)].append(name)
    return {group: sorted(names) for group, names in sorted(grouped.items())}


def _infer_constraint_group(constraint: object) -> str:
    module_name = getattr(constraint, "__module__", "")
    prefix = "jfbench.constraints."
    if isinstance(module_name, str) and module_name.startswith(prefix):
        parts = module_name[len(prefix) :].split(".", maxsplit=1)
        group = parts[0]
        if group and not group.startswith("_"):
            return group
    return "unknown"


def _expand_constraint_counts(
    group_counters: Mapping[str, Counter[str]],
    constraint_catalog: Mapping[str, Sequence[str]],
) -> dict[str, dict[str, int]]:
    expanded: dict[str, dict[str, int]] = {}
    for group, names in sorted(constraint_catalog.items()):
        counter = group_counters.get(group, Counter())
        expanded[group] = {name: int(counter.get(name, 0)) for name in names}
    for group, counter in sorted(group_counters.items()):
        if group not in expanded:
            expanded[group] = {}
        for name, total in sorted(counter.items()):
            if name not in expanded[group]:
                expanded[group][name] = int(total)
    return expanded


def _format_generated_value(value: Any, missing_label: str, empty_label: str) -> str:
    if value is None:
        return missing_label
    text = str(value)
    if text == "":
        return empty_label
    return text


def summarize_dataset_preview(
    rows: Iterable[Mapping[str, Any]],
    max_rows: int = 3,
) -> tuple[list[str], list[Mapping[str, Any]]]:
    sampled_rows: list[Mapping[str, Any]] = []
    columns: list[str] = []
    for row in rows:
        if len(sampled_rows) < max_rows:
            sampled_rows.append(row)
        for key in row:
            key_text = str(key)
            if key_text in columns:
                continue
            columns.append(key_text)
    return columns, sampled_rows


def format_dataset_preview(columns: Sequence[str], rows: Sequence[Mapping[str, Any]]) -> str:
    lines = ["Dataset columns:"]
    if columns:
        for column in columns:
            lines.append(f"  - {column}")
    else:
        lines.append("  (no columns)")
    lines.append("Sample values (up to 3 rows):")
    if rows:
        for idx, row in enumerate(rows, start=1):
            lines.append(f"  [{idx}]")
            if columns:
                for column in columns:
                    lines.append(
                        f"    {column}: {_format_generated_value(row.get(column), '<missing>', '<empty>')}"
                    )
            else:
                lines.append("    (no values)")
    else:
        lines.append("  (no rows)")
    return "\n".join(lines)


def format_generated_records(rows: Sequence[Mapping[str, Any]]) -> Iterable[str]:
    if not rows:
        yield "No generated records to display."
        return
    for idx, row in enumerate(rows, start=1):
        yield f"[{idx}]"
        yield "Prompt source:"
        yield _format_generated_value(
            row.get("prompt_source"),
            "<no prompt source>",
            "<empty prompt source>",
        )
        yield "Constraint count:"
        yield _format_generated_value(
            row.get("constraint_count"),
            "<no constraint count>",
            "<empty constraint count>",
        )
        yield "Constraint types:"
        yield _format_generated_value(
            row.get("constraint_types"),
            "<no constraint types>",
            "<empty constraint types>",
        )
        yield "Prompt:"
        yield _format_generated_value(row.get("prompt"), "<no prompt>", "<empty prompt>")
        yield "Response:"
        yield _format_generated_value(row.get("response"), "<no response>", "<empty response>")
        yield "Reasoning:"
        yield _format_generated_value(
            row.get("reasoning_content"),
            "<no reasoning>",
            "<empty reasoning>",
        )
        yield ""


def main(argv: Sequence[str] | None = None) -> None:
    args = parse_args(argv)
    raw_paths = args.dataset_paths or [DEFAULT_DATASET_PATH]
    dataset_paths = [Path(path).expanduser() for path in raw_paths]
    try:
        files = discover_data_files(dataset_paths)
    except (FileNotFoundError, ValueError) as exc:
        raise SystemExit(str(exc)) from exc
    preview_rows_iter, stats_rows_iter = tee(iter_rows(files))
    preview_columns, preview_rows = summarize_dataset_preview(preview_rows_iter)
    stats = compute_constraint_stats(stats_rows_iter)
    print(format_dataset_preview(preview_columns, preview_rows))
    print()
    print(format_stats(stats))
    if args.show_generated:
        rows = list(iter_rows(files))
        print()
        print("Generated responses:")
        print("-------------------")
        for line in format_generated_records(rows):
            print(line)
        return


if __name__ == "__main__":
    main()
